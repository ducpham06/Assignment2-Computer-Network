#!/usr/bin/env python3
"""Render automation/inventory.yaml from the SoT (no credentials in it, ever)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sot  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPE = {"vios": "cisco_ios", "viosl2": "cisco_ios"}

L = ["# TVI automation inventory -- generated by tools/build_inventory.py from tools/sot.py",
     "# Management addresses are on the out-of-band network 172.16.99.0/24 (EVE-NG Cloud0).",
     "# Credentials are NOT stored here: export TVI_SSH_USER / TVI_SSH_PASS or answer the prompt.",
     "defaults:", "  port: 22", "", "devices:"]
for n, d in sot.DEVICES.items():
    L += [f"  - hostname: {n}",
          f"    ip: {d['mgmt']}",
          f"    device_type: {TYPE[d['platform']]}",
          f"    site: {d['site']}",
          f"    role: {d['role']}",
          f"    lab: {d['lab']}"]
    if d["role"] == "isp":
        L.append("    managed: false   # provider router: backed up, never configured by TVI")
with open(os.path.join(ROOT, "automation", "inventory.yaml"), "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote automation/inventory.yaml")
